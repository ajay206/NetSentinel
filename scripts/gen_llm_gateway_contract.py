"""Regenerate contracts/openapi/llm-gateway.yaml from the FastAPI app.

Usage: uv run python scripts/gen_llm_gateway_contract.py   (or: make llm-gateway-contract)
"""

from __future__ import annotations

from pathlib import Path

import yaml
from llm_gateway.main import app

OUT = Path(__file__).resolve().parents[1] / "contracts/openapi/llm-gateway.yaml"


def main() -> None:
    spec = app.openapi()
    spec["info"]["title"] = "NetSentinel llm-gateway"
    spec["info"]["description"] = (
        "W18: the single entry point for model calls. Routes local SLM first (Ollama), then a "
        "cloud stub until Phase 3, with per-route timeouts and a circuit breaker. Untrusted "
        "turns pass a prompt-injection guard (400 prompt_injection) and PII redaction; callers "
        "need a bearer token and are rate/concurrency limited (401/429). Internal only."
    )
    spec["servers"] = [{"url": "http://localhost:8010"}]
    header = "# Generated by scripts/gen_llm_gateway_contract.py; do not edit by hand.\n"
    OUT.write_text(header + yaml.safe_dump(spec, sort_keys=False, width=100))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
