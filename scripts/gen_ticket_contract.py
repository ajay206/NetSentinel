"""Regenerate contracts/openapi/ticket-service.yaml from the FastAPI app (Step 16).

Usage: uv run python scripts/gen_ticket_contract.py   (or: make ticket-contract)
"""

from __future__ import annotations

from pathlib import Path

import yaml
from ticket_service.main import app

OUT = Path(__file__).resolve().parents[1] / "contracts/openapi/ticket-service.yaml"
HEADER = "# Generated by scripts/gen_ticket_contract.py; do not edit by hand.\n"


def build() -> str:
    spec = app.openapi()
    spec["info"]["title"] = "NetSentinel ticket-service"
    spec["info"]["description"] = (
        "Ticket drafts, human approval (draft -> approved | rejected) and an append-only, "
        "hash-chained audit log (Step 16, ADR-016). Exposed via the gateway as /api/tickets/* "
        "(read: viewer; draft: operator or the MCP service token; approve/reject: operator). "
        "Callers are identified by X-NS-User / X-NS-Role set by the gateway. "
        "Generated from the FastAPI app."
    )
    spec["servers"] = [{"url": "http://localhost:8009"}]
    return HEADER + yaml.safe_dump(spec, sort_keys=False, width=100)


def main() -> None:
    OUT.write_text(build())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
