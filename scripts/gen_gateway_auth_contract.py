"""Regenerate contracts/openapi/api-gateway-auth.yaml (W11 auth + timeline routes).

Only the routes added in W11 are exported; the older proxy routes forward the backend
contracts in contracts/openapi/. Usage: make gateway-contract
"""

from __future__ import annotations

import os
from pathlib import Path

import yaml

os.environ.setdefault("DISABLE_KAFKA", "1")

from api_gateway.main import app  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "contracts/openapi/api-gateway-auth.yaml"
PATHS = ("/api/auth/login", "/api/auth/me", "/api/auth/users", "/api/alarms/timeline")
ROLES = {
    "/api/auth/login": "public (rate limited per IP)",
    "/api/auth/me": "viewer",
    "/api/auth/users": "admin",
    "/api/alarms/timeline": "viewer",
}


def build() -> dict:
    spec = app.openapi()
    paths = {p: spec["paths"][p] for p in PATHS}
    for path, ops in paths.items():
        for op in ops.values():
            op["x-required-role"] = ROLES[path]
            if path != "/api/auth/login":
                op["security"] = [{"bearer": []}]
                op.setdefault("responses", {}).update(
                    {
                        "401": {"description": "Missing, invalid or expired token"},
                        "403": {"description": "Role too low"},
                        "429": {"description": "Rate limited (Retry-After header)"},
                    }
                )
    components = spec.get("components", {})
    components["securitySchemes"] = {
        "bearer": {"type": "http", "scheme": "bearer", "bearerFormat": "JWT (HS256)"}
    }
    return {
        "openapi": spec["openapi"],
        "info": {
            "title": "NetSentinel api-gateway: auth and timeline (W11)",
            "version": spec["info"]["version"],
            "description": (
                "JWT login (HS256), RBAC roles viewer < operator < admin, per-user rate limits. "
                "POST /api/copilot/analyze needs operator; every other /api and /ws route needs "
                "viewer; /health is public. WebSockets pass the token as ?token= and are closed "
                "with 4401/4403/4429. Generated from the FastAPI app."
            ),
        },
        "servers": [{"url": "http://localhost:8000"}],
        "paths": paths,
        "components": components,
    }


def main() -> None:
    header = "# Generated by scripts/gen_gateway_auth_contract.py; do not edit by hand.\n"
    OUT.write_text(header + yaml.safe_dump(build(), sort_keys=False, width=100))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
