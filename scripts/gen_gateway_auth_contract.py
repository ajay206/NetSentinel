"""Regenerate contracts/openapi/api-gateway-auth.yaml (W11 auth + timeline routes).

Only the routes added in W11 are exported; the older proxy routes forward the backend
contracts in contracts/openapi/. Usage: make gateway-contract
"""

from __future__ import annotations

import os
from pathlib import Path

import yaml

os.environ.setdefault("DISABLE_KAFKA", "1")

from api_gateway.main import app  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "contracts/openapi/api-gateway-auth.yaml"
ROLES = {
    "/api/auth/login": "public (rate limited per IP; locks after N failures)",
    "/api/auth/me": "viewer",
    "/api/auth/password": "viewer (any signed-in user)",
    "/api/auth/users": "admin",
    "/api/alarms/timeline": "viewer",
    # Step 13b
    "/api/admin/users": "admin",
    "/api/admin/users/{username}": "admin",
    "/api/admin/users/{username}/unlock": "admin",
    "/api/admin/users/{username}/reset-password": "admin",
    "/api/admin/audit": "admin",
    "/api/admin/settings": "admin",
    "/api/incidents/{incident_id}/actions": "operator",
    "/api/alarms/actions": "operator",
    "/api/alarms/workflow": "viewer",
    # Step 14
    "/api/graph/impact": "viewer",
    "/api/graph/summary": "viewer",
    "/api/graph/queries": "viewer",
    "/api/graph/queries/{name}": "viewer",
    "/api/graph/reload": "admin",
    # Step 15
    "/api/graph/context/{entity_id}": "viewer",
    # Step 16 (reads viewer; drafts operator or the MCP service token; decisions operator)
    "/api/tickets": "viewer",
    "/api/tickets/audit": "viewer",
    "/api/tickets/audit/verify": "viewer",
    "/api/tickets/{ticket_id}": "viewer",
    "/api/tickets/{ticket_id}/audit": "viewer",
    "/api/tickets/drafts": "operator",
    "/api/tickets/{ticket_id}/{decision}": "operator",
    # Step 17 (GET viewer; POST operator; the copilot's service token may POST /api/graph/rca)
    "/api/copilot/runs": "operator",
    "/api/copilot/runs/{run_id}": "viewer",
    "/api/copilot/runs/{run_id}/approval": "operator",
    "/api/graph/rca": "operator",
    "/api/graph/rca/{site_id}": "viewer",
}
PATHS = tuple(ROLES)


def build() -> dict:
    spec = app.openapi()
    paths = {p: spec["paths"][p] for p in PATHS}
    for path, ops in paths.items():
        for op in ops.values():
            op["x-required-role"] = ROLES[path]
            if path != "/api/auth/login":
                op["security"] = [{"bearer": []}]
                op.setdefault("responses", {}).update(
                    {
                        "401": {"description": "Missing, invalid or expired token"},
                        "403": {"description": "Role too low"},
                        "429": {"description": "Rate limited (Retry-After header)"},
                    }
                )
    components = spec.get("components", {})
    components["securitySchemes"] = {
        "bearer": {"type": "http", "scheme": "bearer", "bearerFormat": "JWT (HS256)"}
    }
    return {
        "openapi": spec["openapi"],
        "info": {
            "title": "NetSentinel api-gateway: auth, RBAC admin, workflow and timeline (W11, 13b)",
            "version": spec["info"]["version"],
            "description": (
                "JWT login (HS256), RBAC roles viewer < operator < admin, per-user rate limits. "
                "POST /api/copilot/analyze and the incident/alarm action routes need operator; "
                "/api/admin/* needs admin; every other /api and /ws route needs viewer; /health "
                "is public. Tokens carry a token-version claim (tv): a password change, reset, "
                "role change or disable revokes older tokens (401). Logins lock after "
                "LOGIN_MAX_FAILURES failures (423). WebSockets pass the token as ?token= and are "
                "closed with 4401/4403/4429. Generated from the FastAPI app."
            ),
        },
        "servers": [{"url": "http://localhost:8000"}],
        "paths": paths,
        "components": components,
    }


def main() -> None:
    header = "# Generated by scripts/gen_gateway_auth_contract.py; do not edit by hand.\n"
    OUT.write_text(header + yaml.safe_dump(build(), sort_keys=False, width=100))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
