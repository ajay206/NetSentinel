"""Regenerate contracts/openapi/topology-service.yaml from the FastAPI app (Step 14).

Usage: uv run python scripts/gen_topology_contract.py   (or: make topology-contract)
"""

from __future__ import annotations

from pathlib import Path

import yaml
from topology_service.main import app

OUT = Path(__file__).resolve().parents[1] / "contracts/openapi/topology-service.yaml"
HEADER = "# Generated by scripts/gen_topology_contract.py; do not edit by hand.\n"


def build() -> str:
    spec = app.openapi()
    spec["info"]["title"] = "NetSentinel topology-service"
    spec["info"]["description"] = (
        "Network knowledge graph on Neo4j (Step 14, ADR-014): impact analysis (which sites and "
        "cells lose service if a link, site or node fails) and a catalogue of named read-only "
        "Cypher queries. Exposed via the gateway as /api/graph/* (viewer; reload is admin). "
        "Generated from the FastAPI app."
    )
    spec["servers"] = [{"url": "http://localhost:8008"}]
    return HEADER + yaml.safe_dump(spec, sort_keys=False, width=100)


def main() -> None:
    OUT.write_text(build())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
