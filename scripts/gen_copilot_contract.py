"""Regenerate contracts/openapi/copilot-orchestrator.yaml from the FastAPI app.

Usage: uv run python scripts/gen_copilot_contract.py   (or: make copilot-contract)
"""

from __future__ import annotations

from pathlib import Path

import yaml
from copilot_orchestrator.api import app

OUT = Path(__file__).resolve().parents[1] / "contracts/openapi/copilot-orchestrator.yaml"


def main() -> None:
    spec = app.openapi()
    spec["info"]["title"] = "NetSentinel copilot-orchestrator"
    spec["info"]["description"] = (
        "Simple (non-LangGraph) analyze flow (W9). Evidence (alarms, KPI anomalies, fault type, "
        "runbooks) is gathered through mcp-server tools over MCP (W10, TOOLS=mcp) or directly "
        "over HTTP (TOOLS=http). A local model, reached only via llm-gateway (W18), writes a "
        "JSON answer "
        "that is validated with Pydantic plus citation checks, retried up to 3 times, else a "
        "deterministic fallback is returned. toolCalls lists every evidence call. Exposed via "
        "the gateway as POST /api/copilot/analyze. Generated from the FastAPI app."
    )
    spec["servers"] = [{"url": "http://localhost:8005"}]
    spec["paths"]["/analyze"]["post"]["responses"]["404"] = {
        "description": "No alarms for the site in the window"
    }
    header = "# Generated by scripts/gen_copilot_contract.py; do not edit by hand.\n"
    OUT.write_text(header + yaml.safe_dump(spec, sort_keys=False, width=100))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
